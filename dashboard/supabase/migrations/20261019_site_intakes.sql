-- Website intake: every form a buyer fills on one of the business's sites (corpcover.com Find,
-- and later the enquiry forms on benefixe.com, newsouthsea.com, traderisksolutions.com.sg).
-- One row per submission, keyed by the id the site generates, so partial saves upsert the same row.
-- Lives in the TRS Cloud SQL database (trs-pg, asia-southeast1) behind the PostgREST API.

create table if not exists site_intakes (
  id               uuid primary key,                         -- generated by the site, reused for every save
  site_id          uuid not null references marketing_sites(id),
  kind             text not null default 'find' check (kind in ('find', 'review', 'enquiry', 'chat')),
  status           text not null default 'partial' check (status in ('partial', 'submitted', 'contacted', 'met', 'quoted', 'won', 'lost')),
  company_name     text,
  contact_name     text,
  email            text,
  phone            text,
  industry         text,
  answers          jsonb not null default '{}',
  product_requests jsonb not null default '[]',
  flags            text[] not null default '{}',
  proposal_fields  jsonb not null default '{}',
  documents        jsonb not null default '[]',
  booking          jsonb,
  consent_pdpa_at  timestamptz,
  source_url       text,
  user_agent       text,
  company_id       uuid references companies(id) on delete set null,   -- set when staff link it to a client
  owner_email      text,
  note             text,
  submitted_at     timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create index if not exists site_intakes_site_idx on site_intakes (site_id, created_at desc);
create index if not exists site_intakes_status_idx on site_intakes (status);
create index if not exists site_intakes_email_idx on site_intakes (lower(email));

-- Same grants as the other dashboard tables: the service role reads and writes; nothing public.
grant select, insert, update, delete on site_intakes to service_role;
revoke all on site_intakes from anon;          -- holds names, emails and phone numbers

notify pgrst, 'reload schema';
