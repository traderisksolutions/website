#!/usr/bin/env node
// Database types from the live schema (step 2 of the platform clean-up, 20 Nov 2026).
// Reads PostgREST's OpenAPI description (every table and view, column types, NOT NULL, defaults
// and foreign keys) and writes src/lib/db/database.gen.ts in the shape @supabase/postgrest-js
// types against. Run after every migration and commit the result:
//
//   set -a; source .env.local; set +a; node scripts/gen-db-types.mjs
//
// The database has no public address, so this reads through the same PostgREST the app uses.
import { writeFileSync } from 'node:fs'

const url = process.env.NEXT_PUBLIC_SUPABASE_URL
const key = process.env.SUPABASE_SERVICE_KEY
if (!url || !key) { console.error('NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_KEY must be set (source .env.local).'); process.exit(1) }

const res = await fetch(`${url}/rest/v1/`, { headers: { apikey: key, Authorization: `Bearer ${key}` } })
if (!res.ok) { console.error(`PostgREST answered ${res.status}`); process.exit(1) }
const spec = await res.json()

const quote = s => (/^[A-Za-z_$][\w$]*$/.test(s) ? s : JSON.stringify(s))

/** A column's TypeScript type from its OpenAPI type and Postgres format. */
function tsType(p) {
  if (Array.isArray(p.enum) && p.enum.length) return p.enum.map(v => JSON.stringify(v)).join(' | ')
  if (p.type === 'array') return `(${p.items ? tsType(p.items) : 'unknown'})[]`
  if (p.type === 'boolean') return 'boolean'
  if (p.type === 'integer' || p.type === 'number') return 'number'
  if (p.format === 'json' || p.format === 'jsonb') return 'Json'
  if (p.type === 'string') return 'string'
  return 'Json'
}

const FK = /<fk table='([^']+)' column='([^']+)'\/>/

const tables = [], views = []
for (const name of Object.keys(spec.definitions ?? {}).sort()) {
  const def = spec.definitions[name]
  const required = new Set(def.required ?? [])
  const cols = Object.entries(def.properties ?? {})
  const writable = !!spec.paths?.[`/${name}`]?.post
  const row = cols.map(([c, p]) => `          ${quote(c)}: ${tsType(p)}${required.has(c) ? '' : ' | null'}`)
  const insert = cols.map(([c, p]) => `          ${quote(c)}${required.has(c) && p.default === undefined ? '' : '?'}: ${tsType(p)}${required.has(c) ? '' : ' | null'}`)
  const update = cols.map(([c, p]) => `          ${quote(c)}?: ${tsType(p)}${required.has(c) ? '' : ' | null'}`)
  // PostgREST names a foreign key <table>_<column>_fkey unless the migration named it; embeds
  // with a !hint use that name.
  const rels = cols.flatMap(([c, p]) => {
    const m = FK.exec(p.description ?? '')
    return m ? [`          { foreignKeyName: ${JSON.stringify(`${name}_${c}_fkey`)}; columns: [${JSON.stringify(c)}]; isOneToOne: false; referencedRelation: ${JSON.stringify(m[1])}; referencedColumns: [${JSON.stringify(m[2])}] }`] : []
  })
  const body = [
    `      ${quote(name)}: {`,
    `        Row: {\n${row.join('\n')}\n        }`,
    ...(writable ? [`        Insert: {\n${insert.join('\n')}\n        }`, `        Update: {\n${update.join('\n')}\n        }`] : []),
    `        Relationships: [\n${rels.join(',\n')}${rels.length ? '\n' : ''}        ]`,
    '      }',
  ].join('\n')
  ;(writable ? tables : views).push(body)
}

const rpcs = Object.keys(spec.paths ?? {}).filter(p => p.startsWith('/rpc/')).map(p => p.slice(5)).sort()
const out = `// Generated by scripts/gen-db-types.mjs from the live PostgREST schema. Do not edit by hand.
// ${tables.length} tables, ${views.length} views, ${rpcs.length} functions.

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]

export type Database = {
  public: {
    Tables: {
${tables.join('\n')}
    }
    Views: {
${views.join('\n')}
    }
    Functions: {
${rpcs.map(r => `      ${quote(r)}: { Args: Record<string, unknown>; Returns: unknown }`).join('\n')}
    }
    Enums: { [_ in never]: never }
    CompositeTypes: { [_ in never]: never }
  }
}

export type Tables<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row']
export type Insert<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Insert']
export type Update<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Update']
`
writeFileSync(new URL('../src/lib/db/database.gen.ts', import.meta.url), out)
console.log(`Wrote src/lib/db/database.gen.ts: ${tables.length} tables, ${views.length} views, ${rpcs.length} functions.`)
