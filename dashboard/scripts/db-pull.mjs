#!/usr/bin/env node
// The database schema in code (21 Nov 2026). Turns a schema-only dump of the live database into
// src/db/schema.ts and src/db/relations.ts (Drizzle). Nothing touches the live database: the dump
// is loaded into an in-memory Postgres (PGlite) and drizzle-kit reads that.
//
//   ~/trs-dn-migration/schema-snapshot.sh /tmp/schema.sql     # read-only pg_dump --schema-only
//   node scripts/db-pull.mjs /tmp/schema.sql
//
// Run after every migration and commit the result. PGlite has no pgvector, so vector columns load
// as real[] and are written back as vector(n) here; the two match_* functions and their hnsw
// indexes are skipped (they stay in SQL).
import { PGlite } from '@electric-sql/pglite'
import { pg_trgm } from '@electric-sql/pglite/contrib/pg_trgm'
import { pgcrypto } from '@electric-sql/pglite/contrib/pgcrypto'
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const dump = process.argv[2]
if (!dump) { console.error('usage: node scripts/db-pull.mjs <schema.sql>'); process.exit(1) }

const work = mkdtempSync(join(tmpdir(), 'trs-db-pull-'))
let sql = readFileSync(dump, 'utf8').split('\n').filter(l => !/^\\(un)?restrict /.test(l)).join('\n')

// table -> [column, dimensions], read before vector types are replaced
const vectors = new Map()
let table = ''
for (const line of sql.split('\n')) {
  const t = line.match(/^CREATE TABLE public\.(\w+)/)
  if (t) table = t[1]
  const v = line.match(/^\s+(\w+) public\.vector\((\d+)\)/)
  if (v) vectors.set(table, [v[1], v[2]])
}
sql = sql.replace(/public\.vector\((\d+)\)/g, 'real[]')

const db = new PGlite(join(work, 'pg'), { extensions: { pg_trgm, pgcrypto } })
const skipped = []
for (const block of sql.split(/\n(?=--\n-- Name: )/)) {
  if (/CREATE EXTENSION IF NOT EXISTS vector|COMMENT ON EXTENSION vector/.test(block)) continue
  try { await db.exec(block) } catch (e) {
    skipped.push(`${block.match(/-- Name: ([^;]+); Type: ([^;]+)/)?.slice(1).join(' / ') ?? '?'}: ${String(e.message).slice(0, 80)}`)
  }
}
await db.close()
const expected = /match_(company|knowledge)_chunks|_embedding_idx/
const unexpected = skipped.filter(s => !expected.test(s))
if (unexpected.length) { console.error('Objects that did not load:\n' + unexpected.join('\n')); process.exit(1) }

writeFileSync(join(work, 'drizzle.config.mjs'),
  `export default { dialect: 'postgresql', driver: 'pglite', dbCredentials: { url: ${JSON.stringify(join(work, 'pg'))} }, out: ${JSON.stringify(join(work, 'out'))}, schemaFilter: ['public'] }\n`)
execFileSync('npx', ['drizzle-kit', 'pull', '--config', join(work, 'drizzle.config.mjs')], { stdio: ['ignore', 'ignore', 'inherit'] })

const HEADER = '// Generated by scripts/db-pull.mjs from the live schema. Do not edit; run the script.\n/* eslint-disable @typescript-eslint/no-unused-vars */\n'
let schema = readFileSync(join(work, 'out/schema.ts'), 'utf8')
// vector columns back to vector(n), table by table
for (const [name, [col, dims]] of vectors) {
  const start = schema.indexOf(`pgTable("${name}", {`)
  if (start < 0) { console.error(`table ${name} not found in the pull`); process.exit(1) }
  const end = schema.indexOf('\n})', start)
  const body = schema.slice(start, end).replace(new RegExp(`(\\n\\t${col}: )real\\(\\)\\.array\\(\\)`), `$1vector({ dimensions: ${dims} })`)
  schema = schema.slice(0, start) + body + schema.slice(end)
}
// drizzle-kit writes an empty-string default as a lone quote
schema = schema.replaceAll(".default(')", ".default('')")
// tables whose foreign keys form a cycle make TypeScript infer `any`; a typed callback breaks it
schema = schema.replaceAll('}, (table) => [', '}, (table): PgTableExtraConfigValue[] => [')
// tsvector has no Drizzle type; a custom type keeps it readable
schema = schema.replace(/unknown\("(\w+)"\)/g, 'tsvector("$1")')
schema = schema.replace('from "drizzle-orm/pg-core"', 'from "drizzle-orm/pg-core"\nimport { vector, customType, type PgTableExtraConfigValue } from "drizzle-orm/pg-core"')
schema = schema.replace('import { sql } from "drizzle-orm"\n',
  'import { sql } from "drizzle-orm"\n\nconst tsvector = customType<{ data: string }>({ dataType: () => "tsvector" })\n')
writeFileSync('src/db/schema.ts', HEADER + schema)
writeFileSync('src/db/relations.ts', HEADER + readFileSync(join(work, 'out/relations.ts'), 'utf8'))
rmSync(work, { recursive: true, force: true })
console.log(`src/db/schema.ts written: ${(schema.match(/= pgTable\(/g) ?? []).length} tables, ${vectors.size} vector columns`)
